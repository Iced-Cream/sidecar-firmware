# A breathy, bowed texture at C4 (261.63 Hz, so note 60 plays it at its own pitch): 16 harmonics
# under a two-formant envelope, each with its own slowly drifting level and pitch, a little
# vibrato, bow noise (band-passed noise pulsed by the fundamental) and breath (high band noise),
# made seamlessly loopable (the end crossfades into the start).
#
# Storage: 8-bit mu-law (mu = 255) at 10 kHz, 1.0 s = 10000 bytes. A 24 kHz int16 sample of
# 1.5 s would be 72 KB: over the 64 KB package cap and twice the Teensy's 32 KB plugin arena
# (shared by all user slots), so the texture is kept small. The plugin decodes mu-law through a
# 256-entry table built in init().
#
# Deterministic (a fixed seed, numpy only):  python make_texture.py  -> texture_data.h
import pathlib

import numpy as np

RATE = 10000
SECONDS = 1.0
F0 = 261.6256
SEED = 20261017
MU = 255.0
XFADE = 0.15                  # loop crossfade, seconds

HERE = pathlib.Path(__file__).resolve().parent


def smooth_noise(rng, n, rate_hz, fs):
    """random values rate_hz times a second, joined by cosine interpolation: -1..1, smooth"""
    pts = int(n * rate_hz / fs) + 3
    v = rng.uniform(-1.0, 1.0, pts)
    x = np.arange(n) * rate_hz / fs
    i = np.floor(x).astype(int)
    f = x - i
    w = 0.5 - 0.5 * np.cos(np.pi * f)
    return v[i] * (1 - w) + v[i + 1] * w


def band_noise(rng, n, lo, hi, fs, tilt=0.0):
    """white noise kept between lo and hi Hz (soft edges) in the frequency domain"""
    X = np.fft.rfft(rng.standard_normal(n))
    f = np.fft.rfftfreq(n, 1 / fs)
    g = 1 / (1 + (lo / np.maximum(f, 1e-3)) ** 4) / (1 + (f / hi) ** 4)
    g *= (np.maximum(f, 1.0) / 1000.0) ** tilt
    y = np.fft.irfft(X * g, n)
    return y / (np.std(y) + 1e-12)


def synth(n, fs, rng):
    t = np.arange(n) / fs
    out = np.zeros(n)
    vib = 0.0025 * np.sin(2 * np.pi * 5.1 * t) + 0.004 * smooth_noise(rng, n, 1.5, fs)
    fund_phase = None
    for k in range(1, 17):
        fk = F0 * k
        if fk > 0.42 * fs:
            break
        # two formants (~650 Hz, ~1800 Hz) over a gentle 1/k^0.8 slope
        form = np.exp(-((fk - 650) / 380) ** 2) + 0.6 * np.exp(-((fk - 1800) / 600) ** 2)
        amp = (0.35 + form) / k ** 0.8
        level = amp * (0.6 + 0.4 * smooth_noise(rng, n, 1.0 + 0.4 * k, fs))       # drifting harmonic level
        drift = 0.0015 * k ** 0.5 * smooth_noise(rng, n, 0.7, fs)                  # and a few cents of pitch
        inst = fk * (1 + vib + drift)
        ph = 2 * np.pi * np.cumsum(inst) / fs + rng.uniform(0, 2 * np.pi)
        if k == 1:
            fund_phase = ph
        out += level * np.sin(ph)
    out /= np.max(np.abs(out))
    # bow noise: band-passed, pulsed once a period by the fundamental
    pulse = 0.5 + 0.5 * np.cos(fund_phase)
    bow = band_noise(rng, n, 700, 3200, fs) * (0.3 + 0.7 * pulse ** 2)
    # breath: high, airy, with its own slow swell
    breath = band_noise(rng, n, 2000, 4400, fs, tilt=-0.5) * (0.6 + 0.4 * smooth_noise(rng, n, 0.8, fs))
    swell = 0.85 + 0.15 * smooth_noise(rng, n, 0.6, fs)
    return swell * (out + 0.16 * bow + 0.07 * breath)


def main():
    rng = np.random.default_rng(SEED)
    n = int(RATE * SECONDS)
    x = int(RATE * XFADE)
    y = synth(n + x, RATE, rng)
    # loop: the first x samples crossfade (equal power) with the x after the end
    a = np.arange(x) / x
    loop = y[:n].copy()
    loop[:x] = y[:x] * np.sin(0.5 * np.pi * a) + y[n:n + x] * np.cos(0.5 * np.pi * a)
    loop -= np.mean(loop)
    loop *= 0.89 / np.max(np.abs(loop))      # -1 dBFS
    # 8-bit mu-law
    m = np.sign(loop) * np.log1p(MU * np.abs(loop)) / np.log1p(MU)
    q = np.clip(np.round((m + 1.0) * 127.5), 0, 255).astype(np.uint8)
    lines = [
        "// texture_data.h - GRAIN's built-in texture. GENERATED by make_texture.py: do not edit.",
        "// The sample is our own synthesis, dedicated to the public domain: CC0 1.0 (LICENSE-texture.txt).",
        f"// {SECONDS} s at {RATE} Hz, 8-bit mu-law (mu 255; decode y = q/127.5 - 1, x = sign(y)((1+mu)^|y| - 1)/mu),",
        f"// a bowed, breathy texture at C4 ({F0} Hz), loopable.",
        "#pragma once",
        "#include <stdint.h>",
        f"#define TEX_RATE {RATE}",
        f"#define TEX_LEN {n}",
        f"#define TEX_ROOT_HZ {F0}f",
        "static const uint8_t tex_mulaw[TEX_LEN] = {",
    ]
    for i in range(0, n, 24):
        lines.append("  " + ",".join(str(int(v)) for v in q[i:i + 24]) + ",")
    lines.append("};")
    (HERE / "texture_data.h").write_text("\n".join(lines) + "\n")
    print(f"texture_data.h: {n} samples, {RATE} Hz, {n} bytes")


if __name__ == "__main__":
    main()
