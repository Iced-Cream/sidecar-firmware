def glyphs(src, w, h):
    out = []
    for g in src.replace("\n", "|").split("|"):
        rows = g.split()
        if not rows:
            continue
        assert len(rows) == h and all(len(r) == w for r in rows), (g, w, h)
        out.append([sum(1 << y for y in range(h) if rows[y][x] == "#") for x in range(w)])
    assert len(out) == 64, len(out)
    return out


def write(name, w, h, g):
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, f"{name}.h"), "w") as f:
        f.write(f"// core/ui/fonts/{name}.h - generated by gen_fonts.py (original glyph data, CC0: LICENSE). ASCII 32..95,\n"
                f"// {w} bytes a glyph, one a column, bit 0 the top row.\n#pragma once\n#include <stdint.h>\n\n"
                f"#include \"ui/ui.h\"\n\nnamespace core {{\nnamespace ui {{\n"
                f"UI_ROM const uint8_t k{name.capitalize()}Data[64 * {w}] = {{\n")
        for i, c in enumerate(g):
            ch = chr(32 + i)
            f.write("    " + ", ".join(f"0x{b:02x}" for b in c) + f",   // {ch if ch != chr(92) else 'backslash'}\n")
        f.write("};\n}  // namespace ui\n}  // namespace core\n")


write("font3x5", 3, 5, glyphs(F3, 3, 5))
