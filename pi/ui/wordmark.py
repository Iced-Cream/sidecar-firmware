#!/usr/bin/env python3
"""pi/ui/wordmark.py FONT [OUT_DIR] - sidecar_wordmark.c/.h: "Sidecar" in Archivo Black (the docs site's wordmark face,
SIL OFL 1.1, @fontsource/archivo-black; a .ttf/.woff, e.g. the docs site's node_modules/@fontsource/archivo-black/files/
archivo-black-latin-400-normal.woff) as two alpha bitmaps: an A8 one for the LVGL title bar (lv_image_dsc_t, recoloured)
and a larger A4 one for the boot screen (sidecar_splash.c, high nibble = left pixel). Needs Pillow and fontTools."""
import io, os, sys
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

TEXT = "Sidecar"

def render(font_bytes, px):
    f = ImageFont.truetype(io.BytesIO(font_bytes), px)
    l, t, r, b = f.getbbox(TEXT)
    im = Image.new("L", (r - l + 2, b - t + 2), 0)
    ImageDraw.Draw(im).text((1 - l, 1 - t), TEXT, font=f, fill=255)
    return im

def rows(data, per=16):
    return "\n".join("\t" + ", ".join("0x%02x" % v for v in data[i:i + per]) + "," for i in range(0, len(data), per))

def main():
    src, out = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.abspath(__file__)))
    tt = TTFont(src); tt.flavor = None
    buf = io.BytesIO(); tt.save(buf); fb = buf.getvalue()
    note = next((r.toUnicode() for r in tt["name"].names if r.nameID == 0), "")
    a8 = render(fb, 34)		# the title bar (52 px high)
    a4 = render(fb, 80)		# the boot screen
    p4 = bytearray()
    for y in range(a4.height):
        row = [a4.getpixel((x, y)) >> 4 for x in range(a4.width)] + [0]
        p4 += bytes((row[x] << 4) | row[x + 1] for x in range(0, a4.width, 2))
    hdr = ("// %s - generated by pi/ui/wordmark.py from Archivo Black: %s, SIL Open Font License 1.1\n"
           "// (http://scripts.sil.org/OFL). \"Sidecar\", the wordmark, as alpha bitmaps. Do not edit.\n")
    with open(os.path.join(out, "sidecar_wordmark.h"), "w") as h:
        h.write(hdr % ("pi/ui/sidecar_wordmark.h", note))
        h.write("#ifndef SIDECAR_WORDMARK_H\n#define SIDECAR_WORDMARK_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        h.write("#define WORDMARK_A8_W\t%d\n#define WORDMARK_A8_H\t%d\nextern const uint8_t WordmarkA8[%d];\t// the title bar, 1 byte a pixel\n\n" % (a8.width, a8.height, a8.width * a8.height))
        h.write("#define WORDMARK_A4_W\t%d\n#define WORDMARK_A4_H\t%d\nextern const uint8_t WordmarkA4[%d];\t// the boot screen, 2 pixels a byte (high nibble left)\n\n" % (a4.width, a4.height, len(p4)))
        h.write("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    with open(os.path.join(out, "sidecar_wordmark.c"), "w") as c:
        c.write(hdr % ("pi/ui/sidecar_wordmark.c", note))
        c.write('#include "sidecar_wordmark.h"\n\n')
        c.write("const uint8_t WordmarkA8[%d] = {\n%s\n};\n\n" % (a8.width * a8.height, rows(a8.tobytes())))
        c.write("const uint8_t WordmarkA4[%d] = {\n%s\n};\n" % (len(p4), rows(p4)))
    print("A8 %dx%d, A4 %dx%d (%d bytes)" % (a8.width, a8.height, a4.width, a4.height, len(p4)))

main()
