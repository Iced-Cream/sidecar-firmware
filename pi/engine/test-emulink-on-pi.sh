#!/bin/bash
# pi/engine/test-emulink-on-pi.sh - the emulator-link plan's on-Pi and Ethernet checks that could not run when their
# tasks were built (docs/superpowers/plans/2026-10-14-pi-engine-emulator-link.md: Task 4 Step 5, Task 5, Task 6
# Step 3, Task 7 Steps 2-3). In order, stopping at the first failure with its reason:
#   mac-ip        Task 5 Step 1: the Mac's Ethernet at MAC_IP/NETMASK (else the plan's one user step, then exit)
#   flash         Task 4 Step 5: build, flash; "network: PI_IP/NETMASK", "link: usb", no fault; the USB
#                 regression on the self-test transport (pi_run.py --selftest engines); with RYTM=1 (the Rytm in
#                 OVERBRIDGE mode on the Pi) also the rytmob "gap 0" line and pi_run.py engines
#   ping          Task 5 Step 2: three replies from PI_IP
#   bringup       Task 5 Step 3: rytm-emu (mod build, a scratch copy of the base) with --ob-link 0.0.0.0:7301, the Pi
#                 on :link=tcp: connected, hello granted 7, frames 48000/s +-1 %, midi both ways (no project check:
#                 see step_bringup); the emulator's
#                 reports (host from PI_IP, flags 0x7, usb OUT frames short constant)
#   console       Task 6 Step 3: ":pool=1:pi-test/sine440.wav" -> ok, ":reportlog=1" -> on
#   phase1-tracks Task 7 Step 2: pi/engine/tests/phase1.py tracks (then Read pi/circle/out/phase1-sd-src.png)
#   phase1-gaps   Task 7 Step 3: phase1.py gaps 600 (about 11 minutes)
# Usage:
#   pi/engine/test-emulink-on-pi.sh [all]       every step in order
#   pi/engine/test-emulink-on-pi.sh STEP...     only those (in the order given)
#   pi/engine/test-emulink-on-pi.sh --dry-run   the steps that would run; touches nothing
# Needs: the Pi 4 with the serial bootloader card on /dev/cu.usbserial-* (power-cycled, or running a kernel that
# answers the reboot magic), the Ethernet cable from the Mac's USB hub straight to the Pi, rytm-emu built
# (cargo build --release) with fw/AR173_us_us1.syx. The emulator base (rytm-emu sections/us_us1.v2.snap + .img,
# git-ignored) is regenerated by phase1.py base when missing or unloadable; every emulator run uses a scratch copy,
# and the old sections/us_us1.snap (no longer loads) is never touched. Nothing is flashed to the Rytm; the Mac's
# network is only read. Exit status 0 when every step run passed.
set -uo pipefail
cd "$(dirname "$0")"
REPO=$(git rev-parse --show-toplevel)
EMU=${RYTM_EMU:-$REPO/../rytm-emu}   # rytm-emu beside this checkout
# The addresses (environment; defaults: the personal Mac's manual 192.168.77.1/24). A Mac that cannot set a manual
# IP keeps its self-assigned link-local one: MAC_IP=169.254.x.y PI_IP=169.254.x.z NETMASK=255.255.0.0. The Pi's
# side is built into the kernel (build.sh's PI_IP/PI_NETMASK/EMUHOST: the serial bootloader card's cmdline.txt
# stays as it is), so it holds for every flash this script makes.
MAC_IP=${MAC_IP:-192.168.77.1}
PI_IP=${PI_IP:-192.168.77.2}
NETMASK=${NETMASK:-255.255.255.0}
export PI_NETMASK=$NETMASK EMUHOST=$MAC_IP:7301
export PI_IP
re() { printf '%s' "$1" | sed 's/[.]/\\./g'; }	# an address as a grep -E regex
MAC_RE=$(re "$MAC_IP"); PI_RE=$(re "$PI_IP"); MASK_RE=$(re "$NETMASK")
MASK_HEX=$(printf '0x%02x%02x%02x%02x' ${NETMASK//./ })
MASK_BITS=0; for _o in ${NETMASK//./ }; do while [ "$_o" -gt 0 ]; do MASK_BITS=$((MASK_BITS + _o % 2)); _o=$((_o / 2)); done; done

pass() { echo "PASS  $STEP: $*"; }
fail() { echo "FAIL  $STEP: $*"; echo "test-emulink-on-pi: stopped at $STEP"; exit 1; }

# flash SECS: build the kernel, flash it, log SECS seconds; sets LOG. The banner must be in the log (flashy writes
# its own lines, so a non-empty log proves nothing). TEST_ON_PI_FAKE_LOG=FILE (testing this script only): LOG=FILE.
flash() {
  local secs=$1 out
  [ "$secs" -ge 15 ] || { echo "flash: SECS must be >= 15 (a shorter monitor can leave the Pi wedged)"; exit 2; }
  if [ -n "${TEST_ON_PI_FAKE_LOG:-}" ]; then
    LOG=$TEST_ON_PI_FAKE_LOG
  else
    ./build.sh kernel >/dev/null || fail "build failed (pi/engine/build.sh kernel)"
    local rel try
    for try in 1 2; do
      # As test-on-pi.sh: SECS is the kernel's own run time, from the "go"; an upload not done in 60 s has stalled.
      out=$(FLASH_SECS_AFTER_GO=1 FLASH_GO_WAIT=60 CIRCLE_TREE=circle-engine "$REPO/pi/circle/flash.sh" ../engine "$secs" 2>&1)
      # flashy's lines can follow "log: ...", and a kernel line's CR can precede it: take it wherever it is.
      rel=$(printf '%s\n' "$out" | grep -Eo 'log: out/[A-Za-z0-9._-]+\.log' | tail -1); rel=${rel#log: }
      [ -n "$rel" ] && [ -f "$REPO/pi/circle/$rel" ] || { printf '%s\n' "$out" | tail -5; fail "flash.sh printed no usable 'log: ' line"; }
      LOG="$REPO/pi/circle/$rel"
      echo "      flash: $(grep -Eo 'Finished in [0-9.]+ seconds' "$LOG" | tail -1 || true); log $LOG"
      grep -q 'Finished in' "$LOG" && break	# measured (test-on-pi.sh): a flash into the bootloader now and then stalls
      [ "$try" -eq 1 ] && echo "      flash: the upload stalled - once more"
    done
  fi
  if [ ! -s "$LOG" ] || ! grep -q '==== rytm-pi engine' "$LOG"; then
    fail "no '==== rytm-pi engine' banner after the flash ($LOG) - the Pi is not answering: power-cycle it and rerun"
  fi
}

# expect REGEX WHAT [FILE]: a line matching REGEX (grep -E) in FILE (default LOG).
expect() {
  if grep -Eq "$1" "${3:-$LOG}"; then pass "$2"; else fail "$2 (no line matching /$1/ in ${3:-$LOG})"; fi
}

nofault() {
  if grep -Eiq '\b(exception|abort|panic|assertion failed|out of memory)\b' "$LOG" ||
     LC_ALL=C grep -Eq $'\x1b\\[(1|91)m' "$LOG"; then fail "a fault in the log ($LOG)"; else pass "no fault"; fi
}

pirun() { (cd "$REPO" && uv run python pi/engine/tests/pi_run.py "$@"); }
phase1() { (cd "$REPO" && uv run python pi/engine/tests/phase1.py "$@"); }

# console OUT SECS CMD...: the Pi's console - each CMD written as ":CMD\n", SECS seconds of its log into OUT.
console() {
  local out=$1 secs=$2
  shift 2
  (cd "$REPO" && uv run python - "$out" "$secs" "$@" <<'EOF'
import glob, sys, time
import serial
out, secs, cmds = sys.argv[1], float(sys.argv[2]), sys.argv[3:]
ports = sorted(glob.glob("/dev/cu.usbserial-*"))
if not ports:
    sys.exit("no serial adapter (/dev/cu.usbserial-*)")
s = serial.Serial(ports[0], 921600, timeout=0.2)
with open(out, "w") as f:
    for c in cmds:
        s.write(b":" + c.encode() + b"\n")
        time.sleep(0.2)
    t = time.time()
    while time.time() - t < secs:
        l = s.readline().decode(errors="replace").strip()
        if l:
            f.write(l + "\n")
            f.flush()
EOF
  ) || fail "console: the serial port did not open"
}

THE_USER_STEP='System Settings > Network > the USB hub'"'"'s Ethernet adapter > Details > TCP/IP > Configure IPv4: Manually, IP '"$MAC_IP"', mask '"$NETMASK"' (or, keeping its self-assigned 169.254.x.y: MAC_IP=that PI_IP=169.254.x.z NETMASK=255.255.0.0)'

# ---- Task 5, Step 1: the Mac's side (read only: this script never configures the network)
step_mac_ip() {
  if ifconfig | grep -q "inet $MAC_IP netmask $MASK_HEX"; then
    pass "$(ifconfig | grep -B6 "inet $MAC_IP " | grep -Eo '^[a-z0-9]+:' | tail -1) inet $MAC_IP/$MASK_BITS"
  else
    echo "FAIL  mac-ip: no interface at $MAC_IP netmask $MASK_HEX. The one user step:"
    echo "      $THE_USER_STEP"
    echo "      Then connect the cable from that port straight to the Pi 4's Ethernet port and rerun."
    exit 1
  fi
}

# ---- Task 4, Step 5: build, flash, USB unchanged
# Pass: the network line with the static IP, link usb, engine begin, no fault; the self-test regression (pi_run.py
# --selftest engines, ALL PASS); with RYTM=1 the rytmob line "gap 0" and pi_run.py engines on the Rytm.
step_flash() {
  flash 30
  expect "network: $PI_RE/$MASK_RE" "network: $PI_IP/$NETMASK (static: the kernel's built-in ip=/netmask=)"
  expect 'link: usb' "link: usb (the default)"
  expect 'engine: begin (ok|WITHOUT a card) in [0-9]+ ms' "engine begin"
  nofault
  if [ "${RYTM:-0}" = 1 ]; then
    expect 'rytmob.*gap 0' "the Rytm's Overbridge stream, gap 0 (RYTM=1)"
    pirun engines || fail "pi_run.py engines on the Rytm (its FAIL lines above)"
    pass "pi_run.py engines: ALL PASS"
  fi
  pirun --selftest engines || fail "pi_run.py --selftest engines (its FAIL lines above): the scheduler or network disturbed USB"
  pass "pi_run.py --selftest engines: ALL PASS (the USB path unchanged)"
}

# ---- Task 5, Step 2: the Pi answers
step_ping() {
  if ping -c 3 -t 10 "$PI_IP" >/dev/null 2>&1; then
    pass "ping $PI_IP: replies"
  else
    fail "no ping replies from $PI_IP: read the Pi's log for the GENET 'link up' line, check the cable"
  fi
}

# ---- Task 5, Step 3: the emulator and the Pi on the link (40 s run, the Pi's console read for 30 s)
step_bringup() {
  local tmp
  tmp=$(mktemp -d -t emulink)
  phase1 base --if-needed || fail "phase1.py base: the emulator base could not be made"
  cp "$EMU/sections/us_us1.v2.snap" "$tmp/p1.snap" && cp "$EMU/sections/us_us1.v2.img" "$tmp/p1.img" ||
    fail "copying the base to $tmp"
  (cd "$EMU" && exec ./target/release/rytm fw/AR173_us_us1.syx --card "$tmp/p1.img" --snapshot "$tmp/p1.snap" --headless \
    --usb-host --audio-null --ob-link 0.0.0.0:7301 --after 40 --screenshot "$tmp/p1-0.png" 2>"$tmp/p1.err") &
  EMU_PID=$!
  local emu=$EMU_PID
  trap 'kill "$EMU_PID" 2>/dev/null' EXIT	# a fail (exit 1) or ^C must not leave the emulator running
  sleep 3
  console "$tmp/pi.log" 30 notes=0 out=tracks link=tcp
  wait "$emu"
  trap - EXIT
  echo "      logs: $tmp/pi.log $tmp/p1.err"
  LOG=$tmp/pi.log
  expect "link: tcp to $MAC_RE:7301" "Pi: link: tcp"
  expect "connected to $MAC_RE:7301, hello sent" "Pi: connected, hello sent"
  expect "connected to $MAC_RE:7301, hello yes \(granted 7\)" "Pi: hello yes (granted 7)"
  # No project check here: the mod build sends 10 <project> only around its EXT machines' trigs (measured
  # 2026-10-15: 40 s idle from us_us1.v2, and with PLAY but no CC 15, the host gets only 19s), and the core logs
  # "project:" only on a change. The 10's handling is covered by core/tests/test_host_link.cpp (first, repeat,
  # change); phase1.py --emu-only tracks shows the mod's 10 PRESETS reaching a host over the link.
  local rates
  rates=$(grep -Eo 'hello yes \(granted 7\), frames [0-9]+/s' "$LOG" | grep -Eo '[0-9]+/s' | tr -d '/s' | tail -n +4)
  [ -n "$rates" ] || fail "Pi: no stats lines with frames/s after the start"
  local bad
  bad=$(echo "$rates" | awk '$1 < 47520 || $1 > 48480' | head -3 | tr '\n' ' ')
  if [ -z "$bad" ]; then
    pass "Pi: frames $(echo "$rates" | tail -1)/s (every line after the start within 48000 +-1 %)"
  else
    fail "Pi: frames/s outside 48000 +-1 %: $bad- Circle's TCP send path; record it in docs/pi-engine.md, then raise the 256-frame cap in SendFrames (plan Task 5 Step 3 / Task 7 Step 3)"
  fi
  local min max
  read -r min max < <(grep -Eo 'midi in [0-9]+ B' "$LOG" | grep -Eo '[0-9]+' | awk 'NR==1{a=$1} {b=$1} END{print a+0, b+0}')
  [ "$max" -gt "$min" ] && pass "Pi: midi in growing ($min -> $max B: the mods' 10/19)" || fail "Pi: midi in not growing ($min -> $max B)"
  read -r min max < <(grep -Eo 'out [0-9]+ B dropped' "$LOG" | grep -Eo '[0-9]+' | awk 'NR==1{a=$1} {b=$1} END{print a+0, b+0}')
  [ "$max" -gt 0 ] && pass "Pi: midi out $max B (14/16/17, empty-slot answers)" || fail "Pi: midi out 0 B"
  expect "overbridge link: host connected from $PI_RE:" "emulator: host connected from $PI_IP" "$tmp/p1.err"
  expect 'overbridge link: host hello, flags 0x7' "emulator: host hello, flags 0x7" "$tmp/p1.err"
  local shorts
  shorts=$(grep -Eo 'usb OUT frames short [0-9]+' "$tmp/p1.err" | grep -Eo '[0-9]+$' | tr '\n' ' ')
  local n2 nl
  n2=$(echo "$shorts" | awk '{print $2}')
  nl=$(echo "$shorts" | awk '{print $NF}')
  [ -n "$n2" ] && [ "$n2" = "$nl" ] && pass "emulator: usb OUT frames short constant after the start ($shorts)" ||
    fail "emulator: usb OUT frames short not constant after the start (reports: ${shorts:-none})"
  read -r min max < <(grep -Eo 'midi to host [0-9]+ B' "$tmp/p1.err" | grep -Eo '[0-9]+' | awk 'NR==1{a=$1} {b=$1} END{print a+0, b+0}')
  [ "$max" -gt "$min" ] && pass "emulator: midi to host growing ($min -> $max B)" || fail "emulator: midi to host not growing"
  read -r min max < <(grep -Eo 'from host [0-9]+ B' "$tmp/p1.err" | grep -Eo '[0-9]+' | awk 'NR==1{a=$1} {b=$1} END{print a+0, b+0}')
  [ "$max" -gt 0 ] && pass "emulator: midi from host $max B" || fail "emulator: midi from host 0 B"
}

# ---- Task 6, Step 3: the console extras (the kernel from the flash step still running)
step_console() {
  local tmp
  tmp=$(mktemp -d -t emulink)
  console "$tmp/pi.log" 5 pool=1:pi-test/sine440.wav reportlog=1
  LOG=$tmp/pi.log
  expect 'pool slot 1 = pi-test/sine440.wav: ok' "pool slot 1 = pi-test/sine440.wav: ok"
  expect 'report log on' "report log on"
}

# ---- Task 7, Steps 2-3: the phase 1 acceptance
step_phase1_tracks() {
  phase1 tracks || fail "phase1.py tracks (its FAIL lines above; the plan's decision points: CC 15, grid recording)"
  pass "phase1.py tracks: ALL PASS - now Read pi/circle/out/phase1-sd-src.png (PAT a ROM voice name) and rerun with LT/SRC for SMP = sine440"
}

step_phase1_gaps() {
  phase1 gaps 600 || fail "phase1.py gaps 600 (its FAIL lines above; compare the Pi's tcp frames/s with 48000)"
  pass "phase1.py gaps 600: ALL PASS"
}

ALL="mac-ip flash ping bringup console phase1-tracks phase1-gaps"
DRY=0
if [ "${1:-}" = "--dry-run" ]; then DRY=1; shift; fi
[ "${1:-}" = "all" ] && [ $# -eq 1 ] && set --
STEPS=${*:-$ALL}
for STEP in $STEPS; do
  declare -F "step_${STEP//-/_}" >/dev/null || { echo "unknown step $STEP (have: $ALL)"; exit 2; }
done
if [ "$DRY" -eq 1 ]; then
  i=0
  for STEP in $STEPS; do i=$((i + 1)); echo "$i. $STEP"; done
  echo "test-emulink-on-pi: dry run, nothing flashed (the Pi on $(ls /dev/cu.usbserial-* 2>/dev/null | head -1 || true))"
  exit 0
fi
for STEP in $STEPS; do
  echo "==== $STEP"
  "step_${STEP//-/_}"
done
echo "test-emulink-on-pi: every step passed ($STEPS)"
