#!/bin/bash
# tools/gen_version.sh [OUT]: core/version.h (or OUT) from the VERSION file at the repo root (docs/versioning.md) - the
# version, the short git commit and a dirty flag (tracked files changed). Rewritten only when its content changes, so a
# build that has not moved does not recompile what includes it. Run by every build (core/Makefile, pi/engine/build.sh,
# teensy/setup_core_lib.sh); the file is git-ignored.
set -eo pipefail
R=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:-$R/core/version.h}
V=$(tr -d ' \t\r\n' < "$R/VERSION")
case "$V" in [0-9]*.[0-9]*.[0-9]*) ;; *) echo "VERSION: \"$V\" is not MAJOR.MINOR.PATCH" >&2; exit 1 ;; esac
C=$(git -C "$R" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)
D=0
if [ "$C" != unknown ] && [ -n "$(git -C "$R" status --porcelain --untracked-files=no 2>/dev/null)" ]; then D=1; fi
F="$C"; [ "$D" = 1 ] && F="$C-dirty"
H=$(printf '// core/version.h - generated by tools/gen_version.sh from VERSION; do not edit, not in git.\n#pragma once\n#define SIDECAR_VERSION\t"%s"\n#define SIDECAR_COMMIT\t"%s"\n#define SIDECAR_DIRTY\t%s\n#define SIDECAR_VERSION_FULL\t"%s (%s)"\n' "$V" "$C" "$D" "$V" "$F")
[ "$(cat "$OUT" 2>/dev/null)" = "$H" ] || printf '%s\n' "$H" > "$OUT"
