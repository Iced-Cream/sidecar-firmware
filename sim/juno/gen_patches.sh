#!/bin/bash
# Regenerate juno_patches.h from AMY's amy/juno.py (shorepine/amy, MIT), the
# pinned checkout ../amy/fetch.sh sets up: the Juno-106 factory patches (18
# sysex bytes each) and AMY's per-patch gain trims.
set -e
D=$(cd "$(dirname "$0")" && pwd)
A=$("$D/../amy/fetch.sh")/amy/juno.py
python3 - "$A" "$D/juno_patches.h" <<'PY'
import ast, re, sys
src = open(sys.argv[1]).read()
patches = ast.literal_eval(re.search(r'^_PATCHES = (\[.*?\]\])\s*$', src, re.M).group(1))
gm = ast.literal_eval(re.search(r'_PATCH_GAIN_MODS = (\{.*?\})', src, re.S).group(1))
assert len(patches) == 128
out = ["// The Juno-106's 128 factory patches as its 18 sysex bytes (16 sliders, two",
       "// switch bytes), and AMY's per-patch gain trims - from shorepine/amy",
       "// amy/juno.py (MIT, (c) Brian Whitman, Dan Ellis). Generated by gen_patches.sh.",
       "#pragma once", "#include <stdint.h>", "", "namespace juno {", "",
       "struct FactoryPatch { const char* name; uint8_t b[18]; float gain; };", "",
       "#ifdef PROGMEM   // the Teensy: in flash (read on a patch change), not copied to RAM1",
       "#define JUNO_TABLE PROGMEM", "#else", "#define JUNO_TABLE", "#endif", "",
       "static const FactoryPatch kPatches[128] JUNO_TABLE = {"]
for i, (name, b) in enumerate(patches):
    out.append(f'    {{"{name}", {{{", ".join(str(x) for x in b)}}}, {gm.get(i, 1.0)}f}},')
out += ["};", "", "}  // namespace juno", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(f"wrote {len(patches)} patches to {sys.argv[2]}")
PY
